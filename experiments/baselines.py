"""Baselines that show how much of the result comes from CLIP itself vs. from the side network.

  1. Zero-shot CLIP  - no training at all, CLIP just compares the image with text prompts.
  2. Linear probe    - frozen CLIP final feature + one linear layer (= the side-net model with the side network removed).
  3. Layer-wise probe - the same linear probe on the CLS token after layers 3, 6, 9 and 12,
                        to see which depth of CLIP holds the useful information for each task.

Usage:  python baselines.py cifar10   |   python baselines.py cifake
"""
import os
import sys

import numpy as np
import open_clip
import timm
import torch
from huggingface_hub import hf_hub_download
from sklearn.metrics import roc_auc_score

from common import (CIFAKE_CLASSES, CIFAR10_CLASSES, RESULTS_DIR, Timer, clip_preprocess, extract_clip_features, keep_awake,
                    linear_probe, load_arrays, save_json, to_float)

CIFAR10_TEMPLATES = [
    "a photo of a {}.", "a blurry photo of a {}.", "a low resolution photo of a {}.",
    "a pixelated photo of a {}.", "a photo of the {}.", "a close-up photo of a {}.",
    "a low contrast photo of a {}.", "a photo of a small {}.", "a photo of a big {}.",
    "a jpeg photo of a {}.",
]
TRAIN_LIMIT = {"cifake": 30000}  # 768-d linear probes saturate well before 100k images; keeps the laptop run short
CIFAKE_PROMPTS = {  # index order must match CIFAKE_CLASSES = ['FAKE', 'REAL']
    "FAKE": ["an AI-generated image.", "a synthetic image generated by a computer.", "a fake image made by AI."],
    "REAL": ["a real photo.", "a photograph taken with a camera.", "a real photograph of an object."],
}


def fake_auc(probs, y):
    """AUC for 'is it fake?' (FAKE is label 0 in CIFAKE)."""
    return float(roc_auc_score((y == 0).astype(int), probs[:, 0]))


@torch.no_grad()
def zero_shot(name, x_te, y_te, device):
    # full OpenAI CLIP ViT-B/16 (image + text towers), from the same Hugging Face repo timm loads
    weights = hf_hub_download("timm/vit_base_patch16_clip_224.openai", "pytorch_model.bin")
    model, _, _ = open_clip.create_model_and_transforms("ViT-B-16", pretrained=weights)
    model = model.to(device).eval()
    tok = open_clip.get_tokenizer("ViT-B-16")

    def text_embed(prompts):
        e = model.encode_text(tok(prompts).to(device)).float()
        e = e / e.norm(dim=-1, keepdim=True)
        e = e.mean(0)
        return e / e.norm()

    if name == "cifar10":
        variants = {
            "single_prompt": torch.stack([text_embed([f"a photo of a {c}."]) for c in CIFAR10_CLASSES]),
            "prompt_ensemble": torch.stack([text_embed([t.format(c) for t in CIFAR10_TEMPLATES])
                                            for c in CIFAR10_CLASSES]),
        }
    else:
        variants = {"prompt_ensemble": torch.stack([text_embed(CIFAKE_PROMPTS[c]) for c in CIFAKE_CLASSES])}

    img = []
    for i in range(0, len(x_te), 256):
        x = clip_preprocess(to_float(x_te[i:i + 256], device))
        with torch.amp.autocast("cuda"):
            e = model.encode_image(x).float()
        img.append(e / e.norm(dim=-1, keepdim=True))
    img = torch.cat(img)

    res = {}
    for k, txt in variants.items():
        probs = (100.0 * img @ txt.T).softmax(1).cpu().numpy()
        res[k] = {"test_acc": float((probs.argmax(1) == y_te).mean())}
        if name == "cifake":
            res[k]["auc_fake"] = fake_auc(probs, y_te)
    del model
    torch.cuda.empty_cache()
    return res


def main():
    name = sys.argv[1]
    assert name in ("cifar10", "cifake")
    keep_awake(True)
    device = torch.device("cuda")
    timer = Timer()
    x_tr, y_tr, x_te, y_te = load_arrays(name)
    if name in TRAIN_LIMIT:  # random subset of the training set for the probes (the test set is always complete)
        keep = np.sort(np.random.default_rng(0).permutation(len(y_tr))[:TRAIN_LIMIT[name]])
        x_tr, y_tr = x_tr[keep], y_tr[keep]
    n_classes = 10 if name == "cifar10" else 2
    print(f"[{name}] train {len(y_tr):,}  test {len(y_te):,}  ({timer})", flush=True)

    results = {"dataset": name, "train_images": int(len(y_tr)), "test_images": int(len(y_te))}
    results["zero_shot"] = zero_shot(name, x_te, y_te, device)
    print(f"[{name}] zero-shot: {results['zero_shot']}  ({timer})", flush=True)

    vit = timm.create_model("vit_base_patch16_clip_224.openai", pretrained=True).to(device)
    f_tr = extract_clip_features(vit, x_tr, device)
    f_te = extract_clip_features(vit, x_te, device)
    del vit
    torch.cuda.empty_cache()
    print(f"[{name}] features extracted ({timer})", flush=True)

    results["linear_probe"] = {}
    for key in ["final", "L3", "L6", "L9", "L12"]:
        r = linear_probe(f_tr[key], y_tr, f_te[key], y_te, n_classes, device)
        probs = r.pop("probs").numpy()
        if name == "cifake":
            r["auc_fake"] = fake_auc(probs, y_te)
        results["linear_probe"][key] = r
        print(f"[{name}] linear probe {key}: acc {r['test_acc'] * 100:.2f}%  ({timer})", flush=True)
        if key == "final":
            np.savez(os.path.join(RESULTS_DIR, f"{name}_linear_probe_preds.npz"), probs=probs, y=y_te)

    results["seconds"] = timer.seconds
    save_json(results, f"{name}_baselines.json")
    keep_awake(False)


if __name__ == "__main__":
    main()
